// Ejercicio 1: Calcular total de compra
const precio1 = parseFloat(prompt("Ingrese el precio del primer producto:"));
const precio2 = parseFloat(prompt("Ingrese el precio del segundo producto:"));
const precio3 = parseFloat(prompt("Ingrese el precio del tercer producto:"));
const totalCompra = precio1 + precio2 + precio3;
console.log("El total de su compra es: $" + totalCompra);